def field_link():
    parts = []
    # Board
    bt = m(F.BOARD_T)
    parts.append(box('board', (m(F.BOARD_W), m(F.BOARD_L), bt),
                     pose(0, 0, -bt / 2), F.ONYX))

    wh = m(F.WALL_H)
    wt = m(F.WALL_T)
    wz = wh / 2
    pit_len = F.DIVIDER_Y + 0.5 + F.BOARD_L / 2     # 28 in
    race_len = F.BOARD_L - pit_len                   # 68 in

    # Long walls: one 96 in beam each, gray along the racecourse, black in the pit.
    for side, sx in (('east', 1), ('west', -1)):
        x = sx * (F.BOARD_W / 2 - F.WALL_T / 2)
        parts.append(box_collision(f'wall_{side}_collision', (wt, m(F.BOARD_L), wh), pose(m(x), 0, wz)))
        parts.append(box_visual(f'wall_{side}_race_visual', (wt, m(race_len), wh),
                                pose(m(x), m(F.BOARD_L / 2 - race_len / 2), wz), F.WINTER_CHILL))
        parts.append(box_visual(f'wall_{side}_pit_visual', (wt, m(pit_len), wh),
                                pose(m(x), m(-F.BOARD_L / 2 + pit_len / 2), wz), F.ONYX))
    # End walls fit between the long walls.
    inner_w = m(F.BOARD_W - 2 * F.WALL_T)
    parts.append(box('wall_north', (inner_w, wt, wh),
                     pose(0, m(F.BOARD_L / 2 - F.WALL_T / 2), wz), F.WINTER_CHILL))
    parts.append(box('wall_south_pit', (inner_w, wt, wh),
                     pose(0, m(-F.BOARD_L / 2 + F.WALL_T / 2), wz), F.ONYX))

    # Pit / racecourse divider and center rail.
    parts.append(box('pit_divider', (m(F.DIVIDER_LEN), m(F.DIVIDER_W), m(F.DIVIDER_H)),
                     pose(0, m(F.DIVIDER_Y), m(F.DIVIDER_H) / 2), F.WINTER_CHILL))
    parts.append(box('center_rail', (m(F.RAIL_W), m(F.RAIL_LEN), m(F.RAIL_H)),
                     pose(0, m(F.RAIL_YC), m(F.RAIL_H) / 2), F.WINTER_CHILL))

    # Octagon lane line (white tape).
    pts = F.octagon_vertices()
    for i in range(len(pts)):
        (x0, y0), (x1, y1) = pts[i], pts[(i + 1) % len(pts)]
        length = math.hypot(x1 - x0, y1 - y0) + F.LINE_W
        yaw = math.atan2(y1 - y0, x1 - x0)
        parts.append(box_visual(f'lane_line_{i}', (m(length), m(F.LINE_W), MARK_H),
                                pose(m((x0 + x1) / 2), m((y0 + y1) / 2), MARK_Z, 0, 0, yaw),
                                F.TAPE_WHITE, emissive=0.15))

    # Pit boxes and start box.
    s = m(F.PIT_BOX)
    for n, x in F.PIT_BOX_X.items():
        parts.append(box_visual(f'pit_box_{n}', (s, s, MARK_H),
                                pose(m(x), m(F.PIT_BOX_Y), MARK_Z), F.DELICATE_WHITE, emissive=0.1))
    parts.append(box_visual('start_box', (s, s, MARK_H),
                            pose(m(F.START_BOX_X), m(F.START_BOX_Y), MARK_Z),
                            F.DELICATE_WHITE, emissive=0.1))

    # Checkered start / finish strips in both openings. Only white squares are
    # drawn; the board is already black.
    c = m(F.CHECKER)
    n_cols = int(round(F.OPENING_X1 - F.OPENING_X0))
    for sx, label in ((1, 'start'), (-1, 'finish')):
        for col in range(n_cols):
            for row in range(F.CHECKER_ROWS):
                if (col + row) % 2:
                    continue
                cx = sx * (F.OPENING_X0 + (col + 0.5) * F.CHECKER)
                cy = F.DIVIDER_Y + (row - (F.CHECKER_ROWS - 1) / 2) * F.CHECKER
                parts.append(box_visual(f'checker_{label}_{col}_{row}', (c, c, MARK_H),
                                        pose(m(cx), m(cy), MARK_Z + 0.0002), F.TAPE_WHITE, emissive=0.1))

    # Start flag tower (the flag arm itself is the separate start_flag model).
    th = m(F.FLAG_TOWER_H)
    parts.append(box('flag_tower', (m(1.0), m(1.0), th),
                     pose(m(F.FLAG_TOWER_X), m(F.FLAG_TOWER_Y), m(F.DIVIDER_H) + th / 2),
                     (0.55, 0.40, 0.25)))
    return '\n        '.join(parts)


def start_flag_model():
    arm = m(F.FLAG_ARM_LEN)
    fl_w, fl_h = m(3.0), m(2.0)
    # Model origin is the pivot at the top of the tower. The arm points -x
    # (lying along the divider) when down; pitch +90 deg swings it up.
    return f'''<model name="start_flag">
      <static>true</static>
      {pose(*F.flag_pose(False))}
      <link name="link">
        {box_visual('arm', (arm, 0.006, 0.006), pose(-arm / 2, 0, 0.004), (0.2, 0.2, 0.2))}
        {box_visual('flag', (fl_w, 0.002, fl_h), pose(-arm + fl_w / 2, 0, 0.004 + fl_h / 2),
                    (0.1, 0.85, 0.15), emissive=0.2)}
      </link>
    </model>'''


def include(name, uri, p):
    return f'''<include>
      <name>{name}</name>
      <uri>model://{uri}</uri>
      {pose(*p)}
    </include>'''


def world_sdf():
    incs = []
    for n in F.TAG_IDS:
        incs.append(include(f'pit_tag_{n}', f'apriltag_41h12_{n}', F.tag_pose_pit(n)))
    for n in F.TAG_IDS:
        p = F.tag_pose_start() if n == F.DEFAULT_START_TAG else F.tag_pose_parked(n)
        incs.append(include(f'start_tag_{n}', f'apriltag_41h12_{n}', p))
    defaults = {c: F.default_car_pose(c) for c, _, _ in F.DEFAULT_CARS}
    for i, color in enumerate(F.CAR_COLORS):
        p = defaults.get(color, F.car_pose_parked(i))
        incs.append(include(f'obstacle_{color}', f'plush_car_{color}', p))

    return f'''<?xml version="1.0"?>
<!--
  SoutheastCon 2027 IEEE Stock Car Race field.
  GENERATED by simulation/scripts/generate_field.py from field_spec.py.
  Do not edit by hand: change field_spec.py and re-run the generator.

  Sources: Game Manual Rev 3.0 (10/9/2026), Arena Build Guide AutoCAD drawing
  (6/12/2026). Units: meters. Board top surface is z = 0.
  +x: across the 48 in width (start box side). +y: away from the pit area.

  Dynamic elements, moved at runtime by simulation/scripts/field_manager.py:
    obstacle_<color>   plush cars. Unused cars are parked on the floor at +x.
    start_tag_<id>     start-area AprilTag. The one in the slot is the
                       assigned pit; the others are parked under the floor.
    start_flag         green start flag arm (down / up).
  Fixed: pit_tag_<id> above pit box <id>.
-->
<sdf version="1.9">
  <world name="track">

    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <!-- Needed for the robot's IMU (OAK-D Lite BMI270). -->
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.8 0.8 0.8 1</background>
      <shadows>true</shadows>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 5 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.3 0.2 -1</direction>
    </light>

    <!-- Floor under the board. -->
    <model name="ground_plane">
      <static>true</static>
      <pose>0 0 {f(-m(F.BOARD_T))} 0 0 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>10 10</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>10 10</size></plane></geometry>
          <material>
            <ambient>0.5 0.5 0.5 1</ambient>
            <diffuse>0.5 0.5 0.5 1</diffuse>
          </material>
        </visual>
      </link>
    </model>

    <!-- Board, walls, divider, center rail, lane line, pit/start boxes,
         checkered strips, flag tower. -->
    <model name="field">
      <static>true</static>
      <link name="link">
        {field_link()}
      </link>
    </model>

    {start_flag_model()}

    {chr(10).join('    ' + s for s in incs).lstrip()}

  </world>
</sdf>
'''


def main():
    for n in F.TAG_IDS:
        write_tag_model(n)
    for color, rgb in F.CAR_COLORS.items():
        write_car_model(color, rgb)
    with open(WORLD_PATH, 'w') as fh:
        fh.write(world_sdf())
    print(f'wrote {os.path.relpath(WORLD_PATH)} and models in {os.path.relpath(MODELS_DIR)}')


if __name__ == '__main__':
    main()
