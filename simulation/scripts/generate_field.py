# AprilTag card models
# --------------------------------------------------------------------------
PX_PER_MM = 10


def tag_texture(tag_id, path):
    """White 4 x 4 in card with the 68 mm tag centered, 10 px/mm."""
    card_px = round(F.TAG_CARD * 25.4 * PX_PER_MM)
    cell_px = round(68.0 / 9 * PX_PER_MM)
    tag_px = cell_px * 9
    img = Image.new('L', (card_px, card_px), 255)
    bits = F.TAG_BITS[tag_id]
    off = (card_px - tag_px) // 2
    for r, row in enumerate(bits):
        for c, v in enumerate(row):
            if v == '#':
                img.paste(0, (off + c * cell_px, off + r * cell_px,
                              off + (c + 1) * cell_px, off + (r + 1) * cell_px))
    # Thin cut line so the card edge is visible against a white wall.
    img.paste(170, (0, 0, card_px, 3))
    img.paste(170, (0, card_px - 3, card_px, card_px))
    img.paste(170, (0, 0, 3, card_px))
    img.paste(170, (card_px - 3, 0, card_px, card_px))
    img.save(path)


def write_tag_model(tag_id):
    name = f'apriltag_41h12_{tag_id}'
    d = os.path.join(MODELS_DIR, name)
    tex_dir = os.path.join(d, 'materials', 'textures')
    os.makedirs(tex_dir, exist_ok=True)
    tex = f'tag41h12_{tag_id:05d}.png'
    tag_texture(tag_id, os.path.join(tex_dir, tex))

    card = m(F.TAG_CARD)
    t = m(F.TAG_CARD_T)
    # Model frame: card center, printed face points +x, image "up" is +z.
    # Front face is a textured plane; the card body behind it is plain white.
    sdf = f'''<?xml version="1.0"?>
<!-- Generated by simulation/scripts/generate_field.py. Do not edit by hand. -->
<sdf version="1.9">
  <model name="{name}">
    <static>true</static>
    <link name="link">
      <visual name="card">
        {pose(-t / 2)}
        <geometry><box><size>{f(t)} {f(card)} {f(card)}</size></box></geometry>
        {material((0.95, 0.95, 0.95))}
      </visual>
      <visual name="tag">
        {pose(0.0005, 0, 0, 0, 0, 0)}
        <geometry><plane><normal>1 0 0</normal><size>{f(card)} {f(card)}</size></plane></geometry>
        <material>
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <specular>0 0 0 1</specular>
          <pbr><metal>
            <albedo_map>materials/textures/{tex}</albedo_map>
            <metalness>0</metalness>
            <roughness>1</roughness>
          </metal></pbr>
        </material>
      </visual>
    </link>
  </model>
</sdf>
'''
    with open(os.path.join(d, 'model.sdf'), 'w') as fh:
        fh.write(sdf)
    with open(os.path.join(d, 'model.config'), 'w') as fh:
        fh.write(model_config(name, f'AprilTag {F.TAG_FAMILY} ID {tag_id}, '
                                    f'68 mm print on a 4 x 4 in card.'))


def model_config(name, desc):
    return f'''<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>{desc}</description>
</model>
'''


