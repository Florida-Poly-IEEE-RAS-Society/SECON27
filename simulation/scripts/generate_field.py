def write_car_model(color, rgb):
    name = f'plush_car_{color}'
    d = os.path.join(MODELS_DIR, name)
    os.makedirs(d, exist_ok=True)
    L, W, H = m(F.CAR_L), m(F.CAR_W), m(F.CAR_H)
    mass = F.CAR_MASS
    ixx = mass / 12 * (W * W + H * H)
    iyy = mass / 12 * (L * L + H * H)
    izz = mass / 12 * (L * L + W * W)

    wheel_r = 0.030
    wheel_w = 0.022
    body_w = W - 2 * wheel_w + 0.006
    body_h = H * 0.50
    body_z = wheel_r * 0.6 + body_h / 2
    cab_l = L * 0.62
    cab_h = H - (body_z + body_h / 2)
    cab_z = body_z + body_h / 2 + cab_h / 2
    white = (0.95, 0.95, 0.95)
    glass = (0.55, 0.80, 0.85)

    vis = []
    vis.append(box_visual('body', (L, body_w, body_h), pose(0, 0, body_z), rgb))
    vis.append(box_visual('cabin', (cab_l, body_w * 0.92, cab_h), pose(-L * 0.06, 0, cab_z), rgb))
    vis.append(box_visual('windshield', (0.004, body_w * 0.75, cab_h * 0.6),
                          pose(-L * 0.06 + cab_l / 2, 0, cab_z), glass))
    vis.append(box_visual('rear_window', (0.004, body_w * 0.75, cab_h * 0.6),
                          pose(-L * 0.06 - cab_l / 2, 0, cab_z), glass))
    vis.append(box_visual('bumper_f', (0.01, body_w * 0.9, 0.02), pose(L / 2, 0, wheel_r), white))
    vis.append(box_visual('bumper_r', (0.01, body_w * 0.9, 0.02), pose(-L / 2, 0, wheel_r), white))
    for i, (wx, wy) in enumerate([(1, 1), (1, -1), (-1, 1), (-1, -1)]):
        vis.append(
            f'<visual name="wheel_{i}">'
            f'{pose(wx * (L / 2 - wheel_r - 0.008), wy * (W / 2 - wheel_w / 2), wheel_r, math.pi / 2, 0, 0)}'
            f'<geometry><cylinder><radius>{f(wheel_r)}</radius><length>{f(wheel_w)}</length></cylinder></geometry>'
            f'{material(white)}</visual>')

    sdf = f'''<?xml version="1.0"?>
<!-- Generated by simulation/scripts/generate_field.py. Do not edit by hand. -->
<!-- Melissa & Doug pull-back plush vehicle: 8.55 x 8.2 x 4.5 in. Origin at the
     bottom center, +x is the front. Dynamic, so a robot that hits it pushes it. -->
<sdf version="1.9">
  <model name="{name}">
    <link name="link">
      <inertial>
        {pose(0, 0, H / 2)}
        <mass>{f(mass)}</mass>
        <inertia><ixx>{ixx:.6g}</ixx><iyy>{iyy:.6g}</iyy><izz>{izz:.6g}</izz>
          <ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
      </inertial>
      <collision name="collision">
        {pose(0, 0, H / 2)}
        <geometry><box><size>{f(L)} {f(W)} {f(H)}</size></box></geometry>
        <surface><friction><ode><mu>0.8</mu><mu2>0.8</mu2></ode></friction></surface>
      </collision>
      {chr(10).join('      ' + v for v in vis).lstrip()}
    </link>
  </model>
</sdf>
'''
    with open(os.path.join(d, 'model.sdf'), 'w') as fh:
        fh.write(sdf)
    with open(os.path.join(d, 'model.config'), 'w') as fh:
        fh.write(model_config(name, f'{color} plush race car obstacle.'))


