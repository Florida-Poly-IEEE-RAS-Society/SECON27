#!/usr/bin/env python3
"""Generate the Gazebo field world and game-element models from field_spec.py.

Writes:
    simulation/worlds/track.sdf
    simulation/models/apriltag_41h12_<id>/       (IDs 1-3, textured 4 x 4 in cards)
    simulation/models/plush_car_<color>/         (obstacle cars)

The generated files are checked in, so you only need to run this after
changing field_spec.py:

    python3 simulation/scripts/generate_field.py

The world holds a fixed default layout. field_manager.py moves obstacles and
swaps the start AprilTag at runtime; see simulation/README.md.
"""

import math
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import field_spec as F  # noqa: E402

SIM_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORLD_PATH = os.path.join(SIM_DIR, 'worlds', 'track.sdf')
MODELS_DIR = os.path.join(SIM_DIR, 'models')

m = F.m
BOARD_TOP = 0.0
MARK_H = 0.001          # painted / taped markings, visual only
MARK_Z = 0.0005


def f(v):
    return f'{v:.5f}'.rstrip('0').rstrip('.') if v != 0 else '0'


def pose(x=0.0, y=0.0, z=0.0, roll=0.0, pitch=0.0, yaw=0.0):
    return f'<pose>{" ".join(f(v) for v in (x, y, z, roll, pitch, yaw))}</pose>'


def material(rgb, emissive=0.0):
    r, g, b = rgb
    c = f'{f(r)} {f(g)} {f(b)} 1'
    e = f'<emissive>{f(r * emissive)} {f(g * emissive)} {f(b * emissive)} 1</emissive>' if emissive else ''
    return (f'<material><ambient>{c}</ambient><diffuse>{c}</diffuse>'
            f'<specular>0.05 0.05 0.05 1</specular>{e}</material>')


def box_visual(name, size, p, rgb, emissive=0.0):
    return (f'<visual name="{name}">{p}'
            f'<geometry><box><size>{" ".join(f(s) for s in size)}</size></box></geometry>'
            f'{material(rgb, emissive)}</visual>')


def box_collision(name, size, p):
    return (f'<collision name="{name}">{p}'
            f'<geometry><box><size>{" ".join(f(s) for s in size)}</size></box></geometry>'
            f'</collision>')


def box(name, size, p, rgb, collide=True, emissive=0.0):
    out = box_visual(f'{name}_visual', size, p, rgb, emissive)
    if collide:
        out = box_collision(f'{name}_collision', size, p) + out
    return out


